-- CREAR LA BASE DE DATOS. 
CREATE DATABASE bd_laboratorio_orm;

-- CREAR UN ESQUEMA. 
CREATE SCHEMA inventario; 

-- CREAR LA TABLA tipo_equipo
CREATE TABLE inventario.tipo_equipo ( 
id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
nombre VARCHAR(100) NOT NULL UNIQUE, 
descripcion VARCHAR(250)
);

-- CREAR TABLA equipo
CREATE TABLE inventario.equipo ( 
id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
codigo VARCHAR(50) NOT NULL UNIQUE,
nombre VARCHAR(100) NOT NULL,
marca VARCHAR(100) NOT NULL , 
estado VARCHAR(100) NOT NULL, 
cantidad INT NOT NULL, 
id_tipo BIGINT NOT NULL, 

CONSTRAINT ck_cantidad_valida 
	CHECK (cantidad >=0),
CONSTRAINT fk_equipo_tipo
	FOREIGN KEY (id_tipo) REFERENCES inventario.tipo_equipo(id_tipo),
CONSTRAINT ck_estado_valido
	CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio'))
);

